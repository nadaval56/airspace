#!/usr/bin/env python3
"""סיווג משני לאזורי הפמ"ת — נושא ורצפת גובה.

## למה זה קיים

הסיווג הראשי של הפמ"ת הוא ארבע קטגוריות: אסור, מוגבל, מסוכן, אסור
לכטב"ם. הוא מדויק אבל גס. מי שמטיס רחפן רוצה לדעת מה מתחיל בקרקע ומה
מתחיל ב-4,000 רגל; מי שמתכנן טיסה רוצה להפריד שטחי אש מאסדות גז.

## מה מותר לגזור, ומה לא

**רצפת הגובה** היא נתון מהטבלה. אין כאן פרשנות.

**הנושא** נגזר ממילים שכתובות **במקור** — בשם הרשמי, ובמלל של הפרק
שמתאר את האזור. "שטח אש 209" נושא את המילים "שטח אש"; על LLP01 כתוב
במלל "האזור האסור **מעל שמורת הטבע** 'החולה'". זו קריאה של הכתוב, לא
ניחוש לפי היכרות עם המקום.

## מה השתנה, ולמה

בגרסה הראשונה הנושא נגזר **מהשם בלבד**, ו-89 מתוך 137 אזורים נפלו
ל"ללא סיווג". ההסבר שניתן אז היה נכון לגבי הטבלאות —

    נספח ב': צפון )Y( · מזרח )X( · גובה מזערי · גובה מרבי · שם האזור · קוד זיהוי
    נספח ג': צפון )Y( · מזרח )X( · רדיוס הסגירה · שם האזור · קוד זיהוי

אין בהן עמודת סוג, ייעוד או הערות — אבל **הטבלאות אינן המקור היחיד,
וגם לא המקור הקובע**. הפרק עצמו אומר בעמוד הראשון שבמקרה של סתירה
"יהווה פרק א-17 (מלל) הפרסום הקובע", והמלל אומר על אזורים דברים
שהטבלה משמיטה: שמורת טבע, מכון מחקר, טורבינות, ומי גורם התיאום.

לכן `theme` קורא עכשיו גם את המלל (ראו `aip_narrative`). מה שעדיין
**אינו** נגזר: ניחוש סוג המתקן מהיכרות עם השם. "אשל" נשאר "אשל".

## שתי קטגוריות שאינן מילת סיווג אלא מבנה המקור

`ips` ו-`contact` נגזרות מהוראת התיאום, לא מסוג המתקן. סעיף 1א, שתחתיו
יושבים כל אזורי ה-LLU, מחלק אותם בעצמו לשניים:

    גורם המעוניין להגיש בקשה לטיסה בתוך מרחבים אלו מחויב ליצור קשר עם
    שירות בתי הסוהר... ב. אזורים שאינם תחת אחריות שירות בתי הסוהר, יש
    לתאם מול הגורם המצוין תחת האזור האסור הרלוונטי.

אזור LLU שהמלל אינו נוקב תחתיו גורם — התיאום עליו מול שב"ס, וזו
אמירה של המסמך ולא שלי. **מה שלא נאמר** הוא שהמתקן הוא בית סוהר, ולכן
התווית מדברת על תיאום ולא על כליאה. אזור עם גורם מצוין מקבל `contact`,
והגורם עצמו נשמר בשדה `authority` ומוצג בחלונית.
"""

from __future__ import annotations

# סדר הבדיקה קובע: הראשון שמתאים מנצח. הרשימות מכילות מילים שמופיעות
# בשם הרשמי או במלל הפרק כלשונן.
#
# הסדר אינו שרירותי: מילה ספציפית לפני מילה כללית. "מנחת טיסנים נגבה"
# הוא אתר טיסנים ולא נמל תעופה, ולכן `model` לפני `airport`; "בה"ד
# מג"ב בית חורון" הוא מתקן מג"ב ולכן `police` לפני `military`.
THEME_RULES: list[tuple[str, str, tuple[str, ...]]] = [
    ("firing", "שטחי אש ומטווחים", ("שטח אש", "שטחי אש", "מטווח", 'שט"ן')),
    ("drop", "גלילי הצנחה", ("גליל הצנחה", "גליל ההצנחה")),
    ("balloon", "בלונים", ("בלון",)),
    ("offshore", "אסדות ומתקנים ימיים", ("אסדת", "ים טטיס", "תמר/")),
    ("judea", "יהודה ושומרון", ("יהודה ושומרון",)),
    ("model", "אתרי רחפנים וטיסנים", ("הטסת רחפנים", "טיסנים")),
    # מלל הפרק: "האזור האסור מעל שמורת הטבע 'החולה'". הטבלה כותבת
    # "החולה" בלבד, ולכן שלוש השמורות האלה נראו עד עכשיו כשמות סתם.
    ("nature", "שמורות טבע וגנים לאומיים", ("שמורת הטבע", "שמורת טבע", "גן לאומי")),
    ("energy", "תשתיות אנרגיה", (
        "תחנת כוח", "תחנת אגירה", "בתי הזיקוק", "טורבינות",
    )),
    ("industry", "מפעלים, מחצבות ותעשייה", (
        "מפעל", "מחצבת", "מחצבה", "אזור תעשיה", "אזור תעשייה", "תעשייה",
        "אזור סחר",
    )),
    ("research", "מכונים ומתקני מחקר", ("מכון", "המכון", "מחקר")),
    ("police", "מתקני משטרה ומג\"ב", (
        "מחוז", "מטה ארצי", "מפקדת", "משטרת", "אגף התנועה",
        "מכללה", "להב 433", "תחנת ראשון", 'מג"ב',
    )),
    ("military", "מחנות ומתקנים צבאיים", ("מחנה", 'בה"ד', "מוצב")),
    ("government", "מוסדות שלטון", (
        "קריית הממשלה", "עיריית", "מעון", "השירות המטאורולוגי",
        "השרות המטאורולוגי",
    )),
    ("airport", "נמלי תעופה", ("נמל תעופה", "שדה תעופה")),
    ("transit", "מרחבים ומעברים", ("מרחב", "נקודת גשר")),
]

# שתי הקטגוריות שנגזרות מהוראת התיאום ולא ממילת סיווג — ראו למעלה.
IPS_THEME = "ips"
CONTACT_THEME = "contact"

# הגורם שסעיף 1א קובע כברירת מחדל, כלשונו במסמך.
IPS_AUTHORITY = "שירות בתי הסוהר"

THEME_LABELS = {key: label for key, label, _ in THEME_RULES}
THEME_LABELS[IPS_THEME] = "מתקנים בתיאום שב\"ס"
THEME_LABELS[CONTACT_THEME] = "מתקנים בתיאום גורם ייעודי"
THEME_LABELS["other"] = "ללא סימן סיווג במקור"

# הסף שביקש המשתמש: אזור שרצפתו גבוהה פחות רלוונטי למי שטס נמוך.
FLOOR_SPLIT_FT = 4000

FLOOR_LABELS = {
    "ground": "מהקרקע",
    "low": f"עד {FLOOR_SPLIT_FT:,} רגל",
    "high": f"מעל {FLOOR_SPLIT_FT:,} רגל",
    "unknown": "ללא רצפה מוגדרת",
}

_GROUND_WORDS = ("GND", "MSL", "SFC")

# ברירת המחדל של סעיף 1א חלה על אזורי הכטב"ם, והם היחידים שתחתיו.
_IPS_PREFIX = "LLU"


def theme(name: str | None, narrative: dict | None = None, code: str | None = None) -> str:
    """מפתח הנושא לפי מה שכתוב במקור על האזור.

    `narrative` הוא פריט מ-`aip_narrative.parse_body` — המלל שהפרק
    מקדיש לאזור. `None` פירושו שהמלל לא נקרא בכלל (למשל נספח ד',
    שאין לו מלל), ואז הסיווג נשען על השם לבד.
    """
    # מהמלל נלקח רק **תיאור האזור** ולא כל הפריט: המשך הפריט מזכיר
    # לפעמים אזור אחר ("בחלק החופף לאזור האסור 'הר הבית'"), ומילה
    # שנשאבה משם הייתה מסווגת את האזור הלא נכון.
    title = (narrative or {}).get("title") or ""
    text = f"{name or ''} {title}"

    for key, _, words in THEME_RULES:
        if any(word in text for word in words):
            return key

    if narrative:
        if narrative.get("coordination"):
            return CONTACT_THEME
        if (code or "").startswith(_IPS_PREFIX):
            return IPS_THEME
    return "other"


def floor_feet(lower_limit) -> int | None:
    """רצפת האזור ברגל. `None` כשאין נתון בטבלה."""
    if lower_limit is None:
        return None
    raw = str(lower_limit).strip().upper()
    if not raw or raw == "UNL":
        return None
    if raw in _GROUND_WORDS:
        return 0
    digits = "".join(ch for ch in raw if ch.isdigit())
    return int(digits) if digits else None


def floor_band(lower_limit) -> str:
    """קבוצת הרצפה, לסינון.

    אזורי הכטב"ם בנספח ג' אינם נושאים גובה כלל — ההגבלה שם אינה
    תחומה בגובה אלא ברדיוס. `unknown` הוא זה, ולא "לא ידוע".
    """
    feet = floor_feet(lower_limit)
    if feet is None:
        return "unknown"
    if feet <= 0:
        return "ground"
    return "low" if feet <= FLOOR_SPLIT_FT else "high"


def classify(properties: dict, narrative: dict | None = None) -> dict:
    """מחזיר את שדות הסיווג שיש להוסיף לאזור.

    כשיש מלל, נשמרים ממנו גם גורם התיאום ומשפט התיאום כלשונו — מה
    שהטייס באמת צריך: למי מתקשרים. שדה שאין לו ערך אינו נכתב, כדי
    שהקובץ לא יתמלא ב-null.
    """
    code = properties.get("id")
    key = theme(properties.get("name"), narrative, code)
    fields = {
        "theme": key,
        "floor_band": floor_band(properties.get("lower_limit")),
    }
    if narrative:
        authority = narrative.get("authority")
        coordination = narrative.get("coordination")
        if not authority and not coordination and key == IPS_THEME:
            # ברירת המחדל של סעיף 1א. נכתבת במפורש כדי שהחלונית תאמר
            # למי מתקשרים, ולא תשתוק דווקא במקום שבו המקור לא שתק.
            #
            # **רק** על אזורי `ips`, ובכוונה: על "קריית הממשלה" או
            # "נמל תעופה אילת רמון" גם כן לא מצוין גורם, אבל לשלוח
            # טייס לשב"ס בגלל מתקן שהמקור מזהה אחרת זו טעות שקטה.
            # מה שנשאר ללא זיהוי אחר — עליו ההוראה נאמרה.
            authority = IPS_AUTHORITY
        if authority:
            fields["authority"] = authority
        if coordination:
            fields["coordination"] = coordination
    return fields
